-- ============================================================================
-- 0015 权限收敛：超级管理员只负责"管理管理员"
--
-- 背景（需求方澄清的原始设计意图）：
--   超级管理员**只应具备创建与管理其他管理员的能力**，不参与任何业务；
--   管理员是甲方业务/管理人员，负责"管系统"；运维人员（厂商或甲方运维）
--   才负责"操作资产"。即便是堡垒机本机，也应创建为本机资源交给运维账户
--   走正常授权流程，而不是给管理员留一条特权通道。
--
-- 此前的问题：
--   0009 给 super_admin 授予了**全部权限**（CROSS JOIN 所有权限点），
--   其中包含 ops:*（Web 终端、会话、文件传输）。
--   于是管理员既能审批授权、又能亲自运维目标资产 —— 既是裁判又是运动员，
--   授权与审计的制衡被自己绕过，三权分立形同虚设。
--
-- 本次调整：
--   1) 超级管理员收敛为"管理员的管理者"：仅保留用户（管理员）管理与角色授予，
--      外加必要的只读查看能力；
--   2) 三员彻底移除任何 ops:* 残留（0009 本意如此，这里做一次防御性清理，
--      避免后续有人手工加过权限）。
--
-- 注意：收敛的是**角色权限**，不是账号。若确实需要管理员临时运维，
-- 正确做法是为其另建一个 operator 账号并走工单授权，操作全程留痕。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 超级管理员：只保留管理员管理与基础查看
--
-- 保留项的理由：
--   system:user:*        创建/启停/重置管理员账号——这是超管的核心职责
--   system:role:manage   分配管理员角色（三员的角色由超管授予）
--   system:config:read   查看配置以便排障（只读，不改）
--   system:info:read     查看系统信息（版本、依赖状态）
-- ---------------------------------------------------------------------------
DELETE FROM sys_role_permission
 WHERE role_id IN (SELECT role_id FROM sys_role WHERE role_code = 'super_admin')
   AND perm_id NOT IN (
        SELECT perm_id FROM sys_permission
         WHERE perm_code LIKE 'system:user:%'
            OR perm_code = 'system:role:manage'
            OR perm_code IN ('system:config:read', 'system:info:read', 'system:log:list')
   );

-- ---------------------------------------------------------------------------
-- 2. 三员：移除任何运维类权限
--
-- 0009 的正则本就没有授予，这里是防御性清理：
-- 若此前有人手工加过 ops:*，会被一并收回，确保"管理员不碰资产"是一条
-- 由数据保证的约束，而不是靠约定。
-- ---------------------------------------------------------------------------
DELETE FROM sys_role_permission
 WHERE role_id IN (
        SELECT role_id FROM sys_role
         WHERE role_code IN ('sys_admin', 'sec_admin', 'audit_admin')
       )
   AND perm_id IN (
        SELECT perm_id FROM sys_permission
         WHERE perm_code LIKE 'ops:%'
       );

-- ---------------------------------------------------------------------------
-- 3. 修正角色描述，让界面上的说明与该角色的实际职责一致
-- ---------------------------------------------------------------------------
UPDATE sys_role SET description = '负责管理管理员账号与角色授予；不参与业务运维，日常运维请创建运维人员账号'
 WHERE role_code = 'super_admin';
