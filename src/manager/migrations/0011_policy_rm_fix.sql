-- ============================================================================
-- 0011 修正 rm 类命令策略的覆盖缺陷
--
-- 背景（阶段 8 实测发现）：
--
--   1) 「禁止删除根目录」的正则
--        rm\s+(-[a-zA-Z]*\s+)*(/|/\*|/\s|--no-preserve-root)
--      只要求出现斜杠，未约束斜杠之后的边界，导致
--        rm -rf /tmp/test、rm -f /data/x.db
--      这类**删除普通绝对路径**的正常运维操作被误判为「删除根目录」而直接阻断。
--      危害有两层：一是冤枉正常操作，二是真正的灾难命令淹没在误报里，
--      运维会逐渐习惯"被拦就绕"，策略等于失效。
--
--   2) 同时存在覆盖盲区：`rm -rf *`、`rm -rf ~`、`rm -rf /opt/data`
--      （非系统目录的绝对路径）完全不被拦截，而这些恰是风险最高的批量删除。
--
-- 本次调整思路：
--   * 灾难性操作（删根、删系统关键目录）—— 继续**直接阻断**；
--   * 高风险但正当的操作（删绝对路径、通配符批量删、删家目录）——
--     改为**二次确认**：让操作人明确知道自己要删什么，而不是一刀切封杀。
--     策略的目标是"让危险操作可见"，不是"让运维干不了活"。
--
-- 兼容性：本迁移只 UPDATE/INSERT 策略行，不改表结构，可在线执行。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 修正：禁止删除根目录
--   要求 `/` 或 `/*` 之后必须是空白或行尾，从而不再误伤 /tmp、/data 等路径
-- ---------------------------------------------------------------------------
UPDATE policy_command
SET pattern = 'rm\s+(-[a-zA-Z]+\s+)*(/|/\*)(\s|$)',
    risk_level = 'critical',
    remark = '删除根目录将导致系统不可用（要求 / 后为空白或行尾，避免误伤 /tmp 等路径）',
    update_time = now()
WHERE is_builtin = true
  AND policy_name = '禁止删除根目录';

-- ---------------------------------------------------------------------------
-- 新增：删除绝对路径 / 通配符批量删除 / 删除家目录 —— 二次确认
--
-- priority 20~22 排在阻断规则（10~17）之后、系统操作确认（30+）之前，
-- 保证"该拦的先拦"，再谈确认。
-- ---------------------------------------------------------------------------
INSERT INTO policy_command
    (tenant_id, policy_name, policy_type, match_type, pattern, risk_level, action, priority, enabled, is_builtin, remark)
VALUES
 (0, '删除绝对路径需确认', 'blacklist', 'regex',
  'rm\s+(-[a-zA-Z]+\s+)*/[^\s]', 'warn', 'confirm', 20, true, true,
  '删除绝对路径下的数据风险较高，需二次确认；删根与系统目录由更高优先级规则直接阻断'),

 (0, '通配符批量删除需确认', 'blacklist', 'regex',
  'rm\s+-[a-zA-Z]*[rf][a-zA-Z]*\s+[^|;]*\*', 'danger', 'confirm', 21, true, true,
  '通配符批量删除可能一次清空大量数据，需二次确认'),

 (0, '删除家目录需确认', 'blacklist', 'regex',
  'rm\s+-[a-zA-Z]*[rf][a-zA-Z]*\s+(~|\$HOME)(/|\s|$)', 'danger', 'confirm', 22, true, true,
  '删除家目录会丢失个人数据与配置，需二次确认')
ON CONFLICT (tenant_id, policy_name) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 补充：数据库/备份文件删除需确认（与 0010 的导出告警配套）
--   导出前先删旧备份是常见动作，但删错就是灾难
-- ---------------------------------------------------------------------------
INSERT INTO policy_command
    (tenant_id, policy_name, policy_type, match_type, pattern, risk_level, action, priority, enabled, is_builtin, remark)
VALUES
 (0, '删除备份与数据库文件需确认', 'blacklist', 'regex',
  'rm\s+-[a-zA-Z]*[rf][a-zA-Z]*\s+[^|;]*(\.sql|\.dump|\.bak|\.tar\.gz|\.rdb|/var/lib/mysql|/var/lib/pgsql)',
  'danger', 'confirm', 23, true, true,
  '删除数据库文件或备份文件需二次确认')
ON CONFLICT (tenant_id, policy_name) DO NOTHING;
