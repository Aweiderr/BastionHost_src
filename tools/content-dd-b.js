    'function verifyTotp(userId: number, inputCode: string): VerifyResult {',
    '  const secret = decryptSecret(userId);                  // 从密码机侧解密种子（内存中使用）',
    '  const step = Math.floor(Date.now() / 1000 / 30);        // 当前时间片',
